use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

use crate::references::extractor::Extractor;
use crate::references::layout::RecordLayout;

/// Detection strategy for a file type.
#[derive(Debug, Clone, Copy)]
pub(crate) enum DetectKind {
    /// Match by known INI filename (case-insensitive).
    Ini(&'static str),
    /// Match by known DB filename (case-insensitive).
    Db(&'static [&'static str]),
    /// Match by known REF filename prefix (case-insensitive).
    RefPrefix(&'static str),
    /// Match by known SCR filename (case-insensitive).
    Scr(&'static str),
    /// Match by known SCR filename prefix (case-insensitive).
    ScrPrefix(&'static str),
    /// Match by known DLG filename prefix (case-insensitive).
    DlgPrefix(&'static str),
    /// Match by known PGP filename prefix (case-insensitive).
    PgpPrefix(&'static str),
    /// The extension alone identifies the type; no filename rule is needed.
    ///
    /// Previously these types abused `DetectKind::Db(&[])` ("DB filename that
    /// never matches") to mean "extension only". Making that intent explicit
    /// keeps `detect()` and the GUI detector in agreement.
    Extension,
}

/// JSON shape of a catalog field, derived from record metadata rather than
/// guessed from the field name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FieldType {
    String,
    Integer,
    Number,
    Boolean,
    Array,
    Object,
    Null,
}

impl FieldType {
    /// JSON Schema type token used by `schema generate`.
    pub fn as_schema_type(self) -> &'static str {
        match self {
            FieldType::String => "string",
            FieldType::Integer => "integer",
            FieldType::Number => "number",
            FieldType::Boolean => "boolean",
            FieldType::Array => "array",
            FieldType::Object => "object",
            FieldType::Null => "null",
        }
    }
}

/// One field of a catalogued record, with its JSON shape.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FieldSpec {
    pub name: String,
    pub ty: FieldType,
}

/// Derive field names/shapes from a record's serde representation.
///
/// `serde_json::to_value(T::default())` yields exactly the keys that
/// `extract_fn` emits, so the catalog, schema and templates can no longer
/// drift away from the on-the-wire record.
pub(crate) fn fields_from_default<T: Default + Serialize>() -> Vec<FieldSpec> {
    let value =
        serde_json::to_value(T::default()).expect("record default must be serializable to JSON");
    let serde_json::Value::Object(map) = value else {
        return Vec::new();
    };
    map.into_iter()
        .map(|(name, value)| FieldSpec {
            name,
            ty: FieldType::from_value(&value),
        })
        .collect()
}

/// Same as [`fields_from_default`], but refine each field's JSON shape using
/// the static `RecordLayout` metadata generated by the derive macro. This is
/// the authoritative source for binary records (serde defaults only reveal
/// the shape of the default *value*, not of the field itself).
pub(crate) fn fields_from_layout<T: Default + Serialize + RecordLayout>() -> Vec<FieldSpec> {
    let mut fields = fields_from_default::<T>();
    for field in &mut fields {
        if let Some(def) = T::LAYOUT.fields.iter().find(|def| def.name == field.name) {
            field.ty = FieldType::from_layout_type(def.ty);
        }
    }
    fields
}

/// Curated field list for formats that have neither a serde record nor a
/// static layout (raw map/tileset/sprite payloads, or non-`Default` records).
pub(crate) fn explicit_fields(fields: &[&'static str]) -> Vec<FieldSpec> {
    fields
        .iter()
        .map(|&name| FieldSpec {
            name: name.to_string(),
            ty: FieldType::Integer,
        })
        .collect()
}

impl FieldType {
    fn from_value(value: &serde_json::Value) -> Self {
        match value {
            serde_json::Value::String(_) => FieldType::String,
            serde_json::Value::Bool(_) => FieldType::Boolean,
            serde_json::Value::Number(n) if n.is_f64() => FieldType::Number,
            serde_json::Value::Number(_) => FieldType::Integer,
            serde_json::Value::Array(_) => FieldType::Array,
            serde_json::Value::Object(_) => FieldType::Object,
            serde_json::Value::Null => FieldType::Null,
        }
    }

    pub(crate) fn from_layout_type(ty: &str) -> Self {
        match ty {
            "u8" | "i8" | "u16" | "i16" | "u32" | "i32" => FieldType::Integer,
            "f32" | "f64" => FieldType::Number,
            "bool" => FieldType::Boolean,
            _ if ty.starts_with("string(") => FieldType::String,
            _ if ty.starts_with("padding(") => FieldType::Integer,
            _ if ty.starts_with("InventoryItem(") => FieldType::Object,
            _ if ty == "bytes" || ty.starts_with('[') || ty.starts_with("Nested(") => {
                FieldType::Array
            }
            // `enum_from_*` records their Rust enum name here; derived serde
            // serializes those as the variant name (a JSON string).
            _ => FieldType::String,
        }
    }
}

/// Short Rust type name for a record, used by `list --format json`.
pub(crate) fn record_name<T>() -> &'static str {
    std::any::type_name::<T>()
        .rsplit("::")
        .next()
        .unwrap_or("Unknown")
}

/// A structured validation error with optional record index for arrays.
#[derive(Debug, Clone, Serialize)]
pub struct ValidationError {
    pub record_index: Option<usize>,
    pub message: String,
}

impl std::fmt::Display for ValidationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self.record_index {
            Some(i) => write!(f, "Record {}: {}", i, self.message),
            None => write!(f, "{}", self.message),
        }
    }
}

/// Function pointer types for the file type registry.
pub(crate) type ExtractFn = fn(&Path) -> Result<serde_json::Value, Box<dyn std::error::Error>>;
pub(crate) type PatchFn = fn(&serde_json::Value, &Path) -> Result<(), Box<dyn std::error::Error>>;
pub(crate) type ValidateFn = fn(&serde_json::Value) -> Result<(), Vec<ValidationError>>;

/// A registered file type with detection, extraction, and patching capabilities.
///
/// This is the single declarative catalog entry: key, filenames/extensions,
/// record type, canonical field list, and the GUI editor that owns it all live
/// together so they cannot drift independently.
pub struct FileType {
    pub key: &'static str,
    pub name: &'static str,
    pub description: &'static str,
    pub extensions: &'static [&'static str],
    pub(crate) detect_kind: DetectKind,
    pub extract_fn: ExtractFn,
    pub patch_fn: PatchFn,
    pub validate_fn: Option<ValidateFn>,
    /// Canonical field list, derived from the record's own metadata.
    pub fields: Vec<FieldSpec>,
    /// Short Rust record type name (or `"n/a"` for raw payloads).
    pub record_type: &'static str,
    /// Editor variant name used by the GUI for this key.
    pub editor: &'static str,
}

impl FileType {
    pub fn matches(&self, path: &Path) -> bool {
        match self.detect_kind {
            DetectKind::Ini(name) => detect_filename(path, name),
            DetectKind::Db(names) => detect_db_filename(path, names),
            DetectKind::RefPrefix(prefix) => detect_filename_prefix(path, prefix),
            DetectKind::Scr(name) => detect_filename(path, name),
            DetectKind::ScrPrefix(prefix) => detect_filename_prefix(path, prefix),
            DetectKind::DlgPrefix(prefix) => detect_filename_prefix(path, prefix),
            DetectKind::PgpPrefix(prefix) => detect_filename_prefix(path, prefix),
            DetectKind::Extension => true,
        }
    }

    /// A representative path that `detect()` resolves back to exactly this key.
    /// Used by the catalog/GUI boundary tests.
    pub fn sample_path(&self) -> PathBuf {
        let ext = self.extensions.first().copied().unwrap_or("");
        match self.detect_kind {
            DetectKind::Ini(name) | DetectKind::Scr(name) => PathBuf::from(name),
            DetectKind::Db(names) => PathBuf::from(names.first().copied().unwrap_or("sample")),
            DetectKind::RefPrefix(prefix)
            | DetectKind::ScrPrefix(prefix)
            | DetectKind::DlgPrefix(prefix)
            | DetectKind::PgpPrefix(prefix) => PathBuf::from(format!("{prefix}sample{ext}")),
            DetectKind::Extension => PathBuf::from(format!("sample{ext}")),
        }
    }

    /// Canonical field names for this key.
    pub fn field_names(&self) -> impl Iterator<Item = &str> + '_ {
        self.fields.iter().map(|f| f.name.as_str())
    }
}

/// Result of file type detection.
pub enum DetectResult {
    /// Exactly one type matched.
    Single(&'static FileType),
    /// Multiple types share the extension but none matched by filename — caller must resolve.
    Ambiguous(Vec<&'static FileType>),
    /// No type matched at all (unknown extension).
    None,
}

